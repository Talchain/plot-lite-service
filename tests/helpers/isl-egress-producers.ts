export interface EgressCapture {
  /** The full URL string given to fetch. */
  url: string;
  /** The ISL endpoint path, e.g. `/api/v1/robustness/analyze/v2`. */
  endpoint: string;
  /** The exact string given to fetch as the request body. */
  bodyText: string;
  /** `JSON.parse(bodyText)`. */
  body: unknown;
}

const ISL_BASE_URL = 'https://isl.pinned.test';

function endpointOf(url: string): string {
  return url.startsWith(ISL_BASE_URL) ? url.slice(ISL_BASE_URL.length) : url;
}

let captured: EgressCapture[] = [];
let realFetch: typeof globalThis.fetch | undefined;

/**
 * Replace global fetch with a recorder. Deliberately a PLAIN assignment rather
 * than `vi.stubGlobal`, so this module also runs outside vitest — the same
 * producers are driven by `tools/isl-contract/capture-egress.ts` under tsx to
 * regenerate the fixtures the Python replay driver reads. One harness, one set
 * of bytes; a second hand-written copy for the tool would be the mirror defect
 * this whole slice exists to remove.
 */
export function installEgressCapture(responseBody: unknown = { status: 'ok' }): void {
  captured = [];
  if (realFetch === undefined) realFetch = globalThis.fetch;
  globalThis.fetch = (async (url: unknown, init: { body?: unknown } | undefined) => {
    const bodyText = String(init?.body ?? '');
    captured.push({
      url: String(url),
      endpoint: endpointOf(String(url)),
      bodyText,
      body: JSON.parse(bodyText),
    });
    return {
      ok: true,
      status: 200,
      headers: { get: () => null },
      text: async () => JSON.stringify(responseBody),
      json: async () => responseBody,
    } as unknown as Response;
  }) as typeof globalThis.fetch;
}

export function uninstallEgressCapture(): void {
  if (realFetch !== undefined) globalThis.fetch = realFetch;
  captured = [];
}

export function takeCaptured(): EgressCapture[] {
  const out = captured;
  captured = [];
  return out;
}

export function sha256(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

/**
 * The committed fixture form. `wire_bytes_sha256` pins the EXACT string handed
 * to fetch; `body` is the same content parsed, which is what the Python replay
 * driver feeds to the pinned model (JSON formatting cannot change a Pydantic
 * parse, but it would change a hash, so both are recorded).
 */
export function canonicalEgressFixture(producer: ProducerSpec, capture: EgressCapture): string {
  return `${JSON.stringify(
    {
      _README:
        'GENERATED by tools/isl-contract/capture-egress.ts — do not hand-edit. Regenerate, then re-run tools/isl-contract/replay-through-pinned-model.py.',
      producer: producer.name,
      endpoint: producer.endpoint,
      site: producer.site,
      liveness: producer.liveness,
      note: producer.note,
      wire_bytes_length: capture.bodyText.length,
      wire_bytes_sha256: sha256(capture.bodyText),
      body: capture.body,
    },
    null,
    2,
  )}\n`;
}

function newClient(): ISLClient {
  return new ISLClient({
    baseUrl: ISL_BASE_URL,
    apiKey: 'pinned-test-key',
    timeoutMs: 5_000,
    maxRetries: 1,
  });
}


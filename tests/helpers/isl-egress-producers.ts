/**
 * Drive every PLoT producer that sends a request to ISL, and capture the EXACT
 * bytes handed to `fetch`.
 *
 * Contract step-2 slice 2 (request-side drift pairing). Shared by:
 *   - tests/isl-request-drift-pairing.contract.test.ts  (the standing gate)
 *   - tools/isl-contract/capture-egress.ts              (regenerates the fixtures
 *     that the pinned-model replay driver consumes)
 *
 * WHY THE FETCH BOUNDARY (rule 3 / trap 16). `ISLClient.request()` builds
 * `requestBodyText = JSON.stringify(body)` (client.ts) and hands that exact
 * string to fetch. A harness that asserted on a translator's RETURN value would
 * sit upstream of the boundary and could not see a key re-added downstream —
 * the constraint injector and the flip-probe cloner both mutate after the
 * translator has returned. Everything here is captured at the wire.
 *
 * DETERMINISM is a hard requirement: the same bodies are hashed into
 * `tests/fixtures/isl-pinned/replay-transcript.json` by the Python driver, and
 * the standing test re-derives them and compares hashes. Every input below is
 * therefore fixed — no clocks, no randomness, no ambient env. `request_id` and
 * `seed` are literals.
 */


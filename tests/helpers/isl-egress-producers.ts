/**
 * `metadata` is what PLoT's own normaliser attaches to a constraint node's
 * observed_state (graph-normaliser.ts) so the constraint compiler can read
 * `.operator`. It is PLoT-internal and must not reach ISL. It is not declared on
 * `EngineNodeV3.observed_state`, hence the cast — which is exactly why the
 * pre-slice-6 verbatim forward was invisible to the typechecker.
 */
function nodeWithInternalMetadata(): EngineNodeV3 {
  return {
    id: 'fac_headcount',
    kind: 'factor',
    label: 'Headcount',
    observed_state: {
      value: 0.4,
      std: 0.08,
      baseline: 0.3,
      unit: 'people',
      raw_value: 40,
      cap: 100,
      factor_type: 'quantitative',
      uncertainty_drivers: ['hiring_pipeline'],
      metadata: { operator: '<=', source: 'cee_constraint_node' },
    } as EngineNodeV3['observed_state'],
  } as EngineNodeV3;
}

export function buildGraph(): EngineGraphV3 {
  const nodes: EngineNodeV3[] = [
    nodeWithInternalMetadata(),
    // External factor with a uniform prior → PU synthesised from the range.
    {
      id: 'fac_market',
      kind: 'factor',
      label: 'Market growth',
      category: 'external',
      prior: { distribution: 'uniform', range_min: 0.2, range_max: 0.6 },
    } as EngineNodeV3,
    // Constrained node with no PU of its own → constraint injection fires.
    {
      id: 'fac_cost',
      kind: 'factor',
      label: 'Cost',
      observed_state: { value: 0.55 },
    } as EngineNodeV3,
    // In the graph but with no observed_state, so the translator emits no PU for
    // it — the realistic "insert" branch of the flip probe.
    { id: 'fac_no_obs', kind: 'factor', label: 'Unmeasured' } as EngineNodeV3,
    { id: 'goal_margin', kind: 'outcome', label: 'Margin' } as EngineNodeV3,
  ];

  return {
    nodes,
    edges: [
      {
        from: 'fac_headcount',
        to: 'goal_margin',
        exists_probability: 0.9,
        strength: { mean: 0.5, std: 0.1 },
      },
      {
        from: 'fac_market',
        to: 'goal_margin',
        exists_probability: 0.8,
        strength: { mean: 0.3, std: 0.12 },
      },
      {
        from: 'fac_cost',
        to: 'goal_margin',
        exists_probability: 0.85,
        strength: { mean: -0.4, std: 0.09 },
      },
    ],
  } as EngineGraphV3;
}

/**
 * The `/v1/run` leg reaches ISL through `analyseRobustness`, which consumes the
 * trust-layer `Graph` (edges carry `weight` / `belief_exists` / `strength_std`,
 * not a `strength` object).
 */
function buildV1Graph(): Parameters<ReturnType<typeof createISLService>['analyseRobustness']>[0] {
  return {
    nodes: [
      nodeWithInternalMetadata(),
      { id: 'fac_cost', kind: 'factor', label: 'Cost', observed_state: { value: 0.55, std: 0.05 } },
      { id: 'goal_margin', kind: 'outcome', label: 'Margin' },
    ],
    edges: [
      { from: 'fac_headcount', to: 'goal_margin', weight: 0.5, belief_exists: 0.9, strength_std: 0.1 },
      { from: 'fac_cost', to: 'goal_margin', weight: -0.4, belief_exists: 0.85, strength_std: 0.09 },
    ],
  } as never;
}

const OPTIONS: OptionV3[] = [
  { id: 'opt_a', label: 'Hire', interventions: { fac_headcount: { value: 0.8 } } },
  { id: 'opt_b', label: 'Hold', interventions: { fac_headcount: { value: 0.2 } } },
] as unknown as OptionV3[];

/** Golden-path constraints: `constraint_id` present, `weight` absent. */
const CONSTRAINTS: GoalConstraint[] = [
  { constraint_id: 'c1', node_id: 'fac_cost', operator: '<=', value: 0.7, label: 'Cost cap' },
] as unknown as GoalConstraint[];

/**
 * Caller-supplied `weight`. `PLOT_TO_ISL_CONTRACT.knownUndeclared` exempts
 * `goal_constraints[].weight`, and an exemption for a key no producer can emit
 * is a dead entry that would never be noticed. This variant makes the exemption
 * OBSERVABLE, so the stale-exemption check below is not vacuous.
 */
const CONSTRAINTS_WITH_WEIGHT: GoalConstraint[] = [
  { constraint_id: 'c1', node_id: 'fac_cost', operator: '<=', value: 0.7, label: 'Cost cap', weight: 0.6 },
] as unknown as GoalConstraint[];

function buildV2Request(constraints: GoalConstraint[]): ISLRobustnessRequestV3 {
  const graph = buildGraph();
  const request = toISLRobustnessRequest(
    graph,
    OPTIONS,
    'goal_margin',
    'req_slice2_pairing',
    2000,
    undefined,
    constraints,
    'seed-slice2',
  );
  // /v2/run runs this immediately after building the request (run.ts Phase 4b+);
  // it MUTATES request.parameter_uncertainties, so a translator-only capture
  // would miss the entries it adds.
  injectConstraintParameterUncertainties(request, constraints, graph.nodes, 'goal_margin');
  return request;
}


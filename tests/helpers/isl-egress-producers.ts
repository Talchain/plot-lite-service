export type ProducerLiveness = 'live' | 'dead-no-caller';

export interface ProducerSpec {
  /** Stable fixture name; also the filename under tests/fixtures/isl-pinned/egress/. */
  name: string;
  /** ISL endpoint this producer targets. */
  endpoint: string;
  /** Where the call is made from, file:symbol. */
  site: string;
  /** Whether the producer has a live caller in PLoT at this tip. */
  liveness: ProducerLiveness;
  /** Human note carried into the PR/report. */
  note: string;
  /** Drives the producer; returns every body it put on the wire. */
  run: () => Promise<EgressCapture[]>;
}

/** `createISLService()` reads its config from env at construction. */
function enabledService(): ReturnType<typeof createISLService> {
  process.env.ISL_ENABLE = '1';
  process.env.ISL_BASE_URL = ISL_BASE_URL;
  process.env.ISL_API_KEY = 'pinned-test-key';
  return createISLService();
}

async function runV2Base(constraints: GoalConstraint[]): Promise<EgressCapture[]> {
  await newClient().request({
    endpoint: '/api/v1/robustness/analyze/v2',
    body: buildV2Request(constraints),
    requestId: 'req_slice2_pairing',
  });
  return takeCaptured();
}


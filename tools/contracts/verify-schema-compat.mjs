#!/usr/bin/env node
/**
 * Objective A: Contracts & Ajv alignment verification
 *
 * Verifies schema compatibility between baseline and updated report.v1.schema.json
 */

import { compareSchemas } from '/Users/paulslee/olumi/olumi-tools/packages/schema-compat/src/index.mjs';
import { readFileSync, writeFileSync } from 'fs';

const CONTRACTS_DIR = '/Users/paulslee/olumi/olumi-contracts';

async function main() {
  console.log('GATES: Objective A — schema compatibility check');

  // Baseline: minimal report.v1 structure (pre-Neil IR fields)
  const baseline = {
    schema: 'report.v1',
    meta: { seed: 123456, generated_at: '2025-01-01T00:00:00Z' },
    summary: { option_best: 'Raise price 10%', confidence: 'MEDIUM' },
    kpis: [
      { name: 'Revenue', p10: 1.02, p50: 1.06, p90: 1.11, unit: '×' }
    ]
  };

  // Candidate: new blessed example with Neil IR fields
  const candidate = JSON.parse(
    readFileSync(`${CONTRACTS_DIR}/schemas/examples/report.v1.example.json`, 'utf8')
  );

  const result = compareSchemas(baseline, candidate, { allowAdditions: true });

  const riskLevel = result.breaking.length > 0 ? 'HIGH' :
                   result.typeChanged && result.typeChanged.length > 0 ? 'MEDIUM' :
                   result.added.length > 0 ? 'LOW' : 'NONE';

  // Write report
  const report = {
    schema: 'schema-compat.v1',
    timestamp: new Date().toISOString(),
    baseline: 'report.v1 (pre-Neil IR)',
    candidate: 'report.v1 (with Neil IR fields)',
    risk_level: riskLevel,
    breaking_changes: result.breaking.length,
    type_changes: (result.typeChanged || []).length,
    additions: result.added.length,
    added_fields: result.added.slice(0, 10).map(a => a.path),
    added_count: result.added.length
  };

  writeFileSync('reports/schema-compat/schema-diff.json', JSON.stringify(report, null, 2), 'utf8');

  // Write markdown report
  const markdown = `# Schema Compatibility Report

**Generated**: ${report.timestamp}

## Summary

- **Risk Level**: ${riskLevel}
- **Breaking Changes**: ${report.breaking_changes}
- **Type Changes**: ${report.type_changes}
- **Additive Fields**: ${report.additions}

## Added Fields (Neil IR)

${result.added.filter(a => !a.path.includes('[0]')).map(a => `- \`${a.path}\` (${a.type})`).join('\n')}

## Assessment

${riskLevel === 'LOW'
  ? '✅ All changes are additive. Existing consumers unaffected.'
  : '⚠️ Breaking changes detected. Manual review required.'}

## Neil IR Fields Added

- \`model_averaging\`: BMA results (prior, sampler, seed, K_evaluated, K_used, mass_covered)
- \`confidence.stability\`: Action consistency and sign flip rate
- \`identifiability\`: Causal identification status with adjustment sets
- \`actions[]\`: Available decision actions (id, var, type, value)
- \`reward\`: Reward structure (type: linear, terms with weights)
- \`time\`: Time-series support (reserved, enabled=false)
- \`provenance\`: Data source tracking (nodes, edges with human|llm|auto)

---
Generated by PLoT Engine Gates (Objective A)
`;

  writeFileSync('reports/schema-compat/schema-diff.md', markdown, 'utf8');

  if (riskLevel === 'HIGH' || riskLevel === 'MEDIUM') {
    console.error(`GATES: FAIL — schema incompatible (risk=${riskLevel})`);
    process.exit(1);
  }

  console.log(`GATES: PASS — schema compatible (risk=${riskLevel})`);
  process.exit(0);
}

main().catch(err => {
  console.error('GATES: FAIL — schema compat:', err.message);
  process.exit(1);
});
